function translateDocument(language: LanguageCode) {
  if (typeof document === 'undefined' || language === DEFAULT_LANGUAGE) {
    return;
  }

  const excludedTags = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA']);
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || excludedTags.has(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }

      return node.textContent?.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    },
  });

  const textNodes: Text[] = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode as Text);
  }

  textNodes.forEach((node) => {
    const nextValue = translateText(language, node.textContent ?? '');
    if (nextValue !== node.textContent) {
      node.textContent = nextValue;
    }
  });

  document.querySelectorAll<HTMLElement>('[placeholder], [aria-label], [title]').forEach((element) => {
    (['placeholder', 'aria-label', 'title'] as const).forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (!current) {
        return;
      }

      const translated = translateText(language, current);
      if (translated !== current) {
        element.setAttribute(attribute, translated);
      }
    });
  });
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(DEFAULT_LANGUAGE);

  useEffect(() => {
    setLanguageState(readStoredLanguage());
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    translateDocument(language);

    if (language === DEFAULT_LANGUAGE) {
      return;
    }

    const observer = new MutationObserver(() => {
      translateDocument(language);
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'aria-label', 'title'],
    });

    return () => observer.disconnect();
  }, [language]);

  const setLanguage = useCallback((nextLanguage: LanguageCode, options?: { persistToProfile?: boolean }) => {
    persistLanguage(nextLanguage);
    setLanguageState(nextLanguage);

    if (options?.persistToProfile === false || !window.localStorage.getItem('token')) {
      return;
    }

    void getMyProfile()
      .then((profile) =>
        updateMyProfile({
          firstName: profile.firstName,
          lastName: profile.lastName,
          email: profile.email,
          language: nextLanguage,
        }),
      )
      .then((profile) => {
        persistLanguage(profile.language);
        setLanguageState(profile.language);
      })
      .catch(() => {});
  }, []);

  useEffect(() => {
    if (!window.localStorage.getItem('token')) {
      return;
    }

    let active = true;
    void getMyProfile()
      .then((profile) => {
        if (!active || !isSupportedLanguage(profile.language)) {
          return;
        }

        persistLanguage(profile.language);
        setLanguageState(profile.language);
      })
      .catch(() => {});

    return () => {
      active = false;
    };
  }, []);

  const value = useMemo<I18nContextValue>(() => {
    const t = (key: TranslationKey) => translations[language][key] ?? translations.en[key] ?? key;
    const translateNavLabel = (label: string) => {
      const key = navLabelKeys[label];
      return key ? t(key) : label;
    };

    return { language, setLanguage, t, translateNavLabel };
  }, [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider.');
  }

  return context;
}


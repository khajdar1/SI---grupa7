function isSupportedLanguage(value: unknown): value is LanguageCode {
  return SUPPORTED_LANGUAGES.some((language) => language.code === value);
}

function readStoredLanguage(): LanguageCode {
  if (typeof window === 'undefined') {
    return DEFAULT_LANGUAGE;
  }

  try {
    const rawUser = window.localStorage.getItem('user');
    const userLanguage = rawUser ? (JSON.parse(rawUser) as { language?: unknown }).language : null;
    const storedLanguage = window.localStorage.getItem(STORAGE_KEY);

    if (isSupportedLanguage(userLanguage)) {
      return userLanguage;
    }

    if (isSupportedLanguage(storedLanguage)) {
      return storedLanguage;
    }
  } catch {
    return DEFAULT_LANGUAGE;
  }

  return DEFAULT_LANGUAGE;
}

function persistLanguage(language: LanguageCode) {
  window.localStorage.setItem(STORAGE_KEY, language);

  const rawUser = window.localStorage.getItem('user');
  if (rawUser) {
    try {
      const user = JSON.parse(rawUser) as Record<string, unknown>;
      window.localStorage.setItem('user', JSON.stringify({ ...user, language }));
    } catch {
      window.localStorage.setItem('user', JSON.stringify({ language }));
    }
  }
}

